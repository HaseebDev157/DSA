public class Array_2D_accesselements {
    public static void main(String[] args) {
        int[][] arr = {{25, 34, 76},
                {78, 97, 12},
                {23, 28, 54}};
        System.out.println(arr[0][2]);
        System.out.println(arr[1][2]);
        System.out.println(arr[2][1]);
    }
}
